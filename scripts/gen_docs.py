"""Write the generated reference pages: docs/commands.md (every ue.py command, from its argparse parser) and
docs/helpers.md (the public functions of the editor-side helper modules, read with `ast`, since those modules import
`unreal`, which only exists inside the editor).

    python scripts/gen_docs.py            # rewrite both pages
    python scripts/gen_docs.py --check    # exit code 1 if either page is out of date (CI runs this)

The output depends only on the source, not on the terminal width or the Python version, so --check is stable.
"""
import argparse
import ast
import inspect
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
HELPER_MODULES = ("ueh", "bpedit", "mat", "inputs", "importer", "ui", "validate")


def _cell(text):
    """Text that is safe inside a Markdown table cell."""
    return " ".join(str(text).split()).replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")


# ---------------------------------------------------------------------------- commands

def _subparsers(parser):
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return action
    return None


def _takes_value(action):
    return action.nargs != 0


def _metavar(action):
    if action.metavar:
        return action.metavar if isinstance(action.metavar, str) else " ".join(action.metavar)
    if action.option_strings:
        return action.dest.upper()
    return action.dest


def _usage_part(action):
    if not action.option_strings:
        name = _metavar(action)
        if action.choices and not action.metavar:
            name = "{" + ",".join(action.choices) + "}"
        return {"?": f"[{name}]", "*": f"[{name} ...]", "+": f"{name} [{name} ...]"}.get(action.nargs, name)
    flag = max(action.option_strings, key=len)
    if not _takes_value(action):
        return f"[{flag}]"
    value = _metavar(action)
    if action.nargs in ("+", "*"):
        value = f"{value} [{value} ...]" if action.nargs == "+" else f"[{value} ...]"
    return f"[{flag} {value}]"


def _visible(parser):
    return [a for a in parser._actions
            if not isinstance(a, (argparse._HelpAction, argparse._SubParsersAction)) and a.help != argparse.SUPPRESS]


def _argument_rows(parser):
    rows = []
    for action in _visible(parser):
        if action.option_strings:
            name = ", ".join(f"`{s}`" for s in action.option_strings)
            if _takes_value(action):
                name += f" {_metavar(action)}"
        else:
            name = f"`{_metavar(action)}`"
        notes = [action.help or ""]
        if action.choices:
            notes.append("One of: " + ", ".join(f"`{c}`" for c in action.choices) + ".")
        if (_takes_value(action) and action.default not in (None, argparse.SUPPRESS, [], "")
                and "default" not in (action.help or "").lower()):
            notes.append(f"Default: `{action.default}`.")
        if isinstance(action, argparse._AppendAction):
            notes.append("Repeatable.")
        rows.append(f"| {_cell(name)} | {_cell(' '.join(n for n in notes if n))} |")
    return rows


def commands_markdown():
    sys.path.insert(0, str(ROOT))
    import ue
    parser = ue.build_parser()
    out = ["# Command reference", "",
           "<!-- Generated by scripts/gen_docs.py from ue.py's argument parser. Don't edit by hand: change the help",
           "     text in ue.py, then run `python scripts/gen_docs.py`. -->", "",
           "Every command of `ue.py` with its arguments. `ue.py -h` and `ue.py <command> -h` print the same help. Below,",
           "`ue.py` means `python <toolkit folder>/ue.py` (or `ue` when installed with pipx).", "",
           "```text", inspect.cleandoc(ue.__doc__), "```", "",
           "## Options for every command", "",
           "```text", "ue.py " + " ".join(_usage_part(a) for a in _visible(parser)) + " COMMAND ...", "```", "",
           "| Option | Description |", "|---|---|", *_argument_rows(parser), ""]
    commands = _subparsers(parser).choices
    help_of = {a.dest: a.help for a in _subparsers(parser)._choices_actions}
    out += ["## Commands", ""]
    out += [f"- [`{name}`](#{name}): {_cell(help_of.get(name) or '')}" for name in commands]
    out.append("")
    for name, sub in commands.items():
        out += [f"### {name}", "", (help_of.get(name) or "").strip(), "",
                "```text", " ".join(["ue.py", name] + [_usage_part(a) for a in _visible(sub)]), "```", ""]
        rows = _argument_rows(sub)
        if rows:
            out += ["| Argument | Description |", "|---|---|", *rows, ""]
    return "\n".join(out)


# ---------------------------------------------------------------------------- helpers

def _signature(node, method=False):
    args = node.args
    if method and args.posonlyargs + args.args:
        args = ast.arguments(posonlyargs=args.posonlyargs[1:], args=args.args[1:] if not args.posonlyargs else args.args,
                             vararg=args.vararg, kwonlyargs=args.kwonlyargs, kw_defaults=args.kw_defaults,
                             kwarg=args.kwarg, defaults=args.defaults)
    return f"{node.name}({ast.unparse(args)})"


def _doc_block(doc):
    if not doc:
        return ["*(no docstring)*", ""]
    doc = inspect.cleandoc(doc)
    if "\n" not in doc:
        return [doc, ""]
    return ["```text", doc, "```", ""]


def _public(name):
    return not name.startswith("_")


def _exported(tree):
    """The module's __all__ if it lists one, else None (every public name)."""
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets):
            try:
                return set(ast.literal_eval(node.value))
            except ValueError:
                return None
    return None


def _module_markdown(name):
    path = ROOT / "editor" / f"{name}.py"
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    exported = _exported(tree)

    def wanted(n):
        return _public(n) and (exported is None or n in exported)

    out = [f"## {name}", "", f"`editor/{name}.py`", ""]
    module_doc = ast.get_docstring(tree)
    if module_doc:
        out += ["<details><summary>Module notes</summary>", "", "```text", module_doc, "```", "", "</details>", ""]
    functions = [n for n in tree.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and wanted(n.name)]
    classes = [n for n in tree.body if isinstance(n, ast.ClassDef) and wanted(n.name)]
    for node in functions:
        out += [f"### `{name}.{_signature(node)}`", "", *_doc_block(ast.get_docstring(node))]
    for node in classes:
        bases = ", ".join(ast.unparse(b) for b in node.bases)
        out += [f"### class `{name}.{node.name}`" + (f" ({bases})" if bases else ""), "",
                *_doc_block(ast.get_docstring(node))]
        for item in node.body:
            if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)) and _public(item.name):
                is_property = any(ast.unparse(d) == "property" for d in item.decorator_list)
                is_static = any(ast.unparse(d) == "staticmethod" for d in item.decorator_list)
                title = (f"{node.name}.{item.name}" if is_property
                         else f"{node.name}.{_signature(item, method=not is_static)}")
                out += [f"#### `{title}`" + (" (property)" if is_property else ""), "",
                        *_doc_block(ast.get_docstring(item))]
    return out


def helpers_markdown():
    out = ["# Helper reference", "",
           "<!-- Generated by scripts/gen_docs.py from the docstrings in editor/. Don't edit by hand: change the",
           "     docstrings, then run `python scripts/gen_docs.py`. -->", "",
           "The public functions of the editor-side helper modules, with their signatures and docstrings. In",
           "`ue.py py` they are pre-imported under these names (`ueh.spawn(...)`, `mat.build(...)`); `ueh.help()` lists",
           "`ueh`'s in the editor.", ""]
    out += [f"- [{name}](#{name})" for name in HELPER_MODULES] + [""]
    for name in HELPER_MODULES:
        out += _module_markdown(name)
    return "\n".join(out)


# ---------------------------------------------------------------------------- main

PAGES = {"commands.md": commands_markdown, "helpers.md": helpers_markdown}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="don't write; exit 1 if a page is out of date")
    args = parser.parse_args(argv)
    stale = []
    for filename, make in PAGES.items():
        path = DOCS / filename
        text = make().rstrip("\n") + "\n"
        current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(filename)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(text.encode("utf-8"))
            print(f"wrote {path.relative_to(ROOT).as_posix()}")
    if stale:
        print("Out of date: " + ", ".join(f"docs/{f}" for f in stale) + ". Run `python scripts/gen_docs.py`.",
              file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
